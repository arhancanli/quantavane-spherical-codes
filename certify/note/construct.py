"""A model of the code X* of (22,116) in the circle geometry of the projective line over F9, built from the group
PGammaL(2,9) alone, and an exact check that it reproduces the class matrix of X*.

  python3 -I certify/note/construct.py

The model uses no data of X*.  Pi = F9 u {inf} with F9 = F3[w]/(w^2 - w - 1) (w is primitive); Gamma = PGammaL(2,9)
acts on Pi and is generated by x -> x + 1, w x, 1/x, x^3 (order 1440 is checked).  The circles are the 30 images of
F3 u {inf}; at a point p the 12 circles through p fall into 4 pencils of 3 circles that pairwise meet only at p.  At
p = inf the pencils are the parallel classes of lines of the affine plane F9 = F3^2; the pencil of direction d is
perpendicular to that of direction d' if (d'/d)^2 = -1; Gamma_inf = AGammaL(1,9) preserves this relation, and Gamma
transports it to every point.

  A: the 72 pentads, i.e. the orbits on Pi of the elements of order 5 of Gamma;
  B: the 40 pairs beta = (p, {pi, pi'}) of a point p and two pencils at p that are not perpendicular;
  P = {p+, p-} and Q = {q+, q-}.

A6 = PSL(2,9) (generated by x + 1, w^2 x, -1/x) has two orbits on A and two on B; the elements of Gamma that preserve
each A6-orbit on A form M10 (checked by its element orders), and the others act on P and Q by swapping the two points.  For a pentad O and a pencil pi at a
point p, call pi of type I for O if exactly one circle of pi meets O in exactly 3 points.  B+ is the A6-orbit of
beta0 = (inf, {pencil of direction 1, pencil of direction w}); A+ is the A6-orbit of the pentads O containing inf for
which both pencils of beta0 are of type I.  The class (index k of the value t_k of the note's Table 1; 12 = contact)
of a pair is given by RULES:

  A x A   |O n O'| = 0 or 2: 12; = 1 or 4: 5; = 3: 12 in the same A6-orbit, 5 otherwise
  B x B   same point: 8 if the two pairs of pencils are disjoint, 2 otherwise; different points p, q: 6 if the pair of
          pencils at p, moved to q along the circles through p and q, is the pair at q; 12 otherwise
  A x B   both pencils of beta of type I for O: 3; both not of type I: 10; one of each: 12
  A x P   <O, p_s>: 9 if O in A_s, 12 otherwise        A x Q   <O, q_s>: 7 if O in A_s, 12 otherwise
  B x P   <beta, p_s>: 12 if beta in B_s, 4 otherwise  B x Q   <beta, q_s>: 12 if beta in B_s, 11 otherwise
  P x Q   <p_s, q_r>: 1 if s = r, 0 otherwise          P x P, Q x Q: 12

Checks: (1) |Gamma| = 1440, 30 circles, 4 pencils of 3 circles at each point, 72 pentads, 40 pairs, two A6-orbits on A
and on B; (2) Gamma preserves the model class matrix (so Gamma acts by automorphisms of the model); (3) an exhaustive
isomorphism search (aut116.isomorphism) finds a relabelling pi with C_model[pi(a), pi(b)] = C[a, b] for all a, b, where
C is data/class_matrix.gp, and this equality is then checked entry by entry.  Since the Gram matrix of X* is
I + sum_k t_k A_k (A_k the 0/1 matrix of class k), X* is congruent to the configuration whose Gram matrix is given by
RULES and the values t_k.  Writes out/construct.json (with the relabelling, model point names and the counts).
"""
import collections, hashlib, itertools, json, os, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [p for p in os.environ.get("QV_LIBS", "").split(os.pathsep) if p]   # optional library folders
sys.path.insert(0, HERE)
import numpy as np
from aut116 import load_classes, isomorphism

# ---------------------------------------------------------------- F9 = F3[w]/(w^2 - w - 1), elements (a, b) = a + b w
F = [(a, b) for a in range(3) for b in range(3)]
ZERO, ONE, W = (0, 0), (1, 0), (0, 1)


def add(x, y):
    return ((x[0] + y[0]) % 3, (x[1] + y[1]) % 3)


def neg(x):
    return ((-x[0]) % 3, (-x[1]) % 3)


def mul(x, y):          # (a + b w)(c + d w) = (ac + bd) + (ad + bc + bd) w, as w^2 = w + 1
    a, b = x
    c, d = y
    return ((a * c + b * d) % 3, (a * d + b * c + b * d) % 3)


def pw(x, k):
    r = ONE
    for _ in range(k):
        r = mul(r, x)
    return r


def inv(x):
    return next(y for y in F if mul(x, y) == ONE)


INF = "inf"
PI = [INF] + F
IDX = {p: i for i, p in enumerate(PI)}


def semilinear(a, b, c, d, frob):
    """x -> (a x^s + b)/(c x^s + d), s = 3 if frob else 1, as a tuple of indices of PI."""
    out = []
    for p in PI:
        if p == INF:
            img = INF if c == ZERO else mul(a, inv(c))
        else:
            x = pw(p, 3) if frob else p
            num, den = add(mul(a, x), b), add(mul(c, x), d)
            img = INF if den == ZERO else mul(num, inv(den))
        out.append(IDX[img])
    return tuple(out)


def closure(gens):
    e = tuple(range(len(gens[0])))
    G, todo = {e}, [e]
    while todo:
        x = todo.pop()
        for s in gens:
            y = tuple(s[i] for i in x)
            if y not in G:
                G.add(y)
                todo.append(y)
    return sorted(G)


def porder(g):
    k, h, e = 1, g, tuple(range(len(g)))
    while h != e:
        h, k = tuple(g[i] for i in h), k + 1
    return k


def main():
    t0 = time.time()
    rep = {"program": "construct.py",
           "code_sha256": hashlib.sha256(open(os.path.abspath(__file__), "rb").read()).hexdigest()}
    assert len({pw(W, k) for k in range(8)}) == 8                       # w is primitive
    GEN = [semilinear(ONE, ONE, ZERO, ONE, 0), semilinear(W, ZERO, ZERO, ONE, 0),
           semilinear(ZERO, ONE, ONE, ZERO, 0), semilinear(ONE, ZERO, ZERO, ONE, 1)]
    GAMMA = closure(GEN)
    W2 = pw(W, 2)
    A6 = closure([semilinear(ONE, ONE, ZERO, ONE, 0), semilinear(W2, ZERO, ZERO, ONE, 0),
                  semilinear(ZERO, neg(ONE), ONE, ZERO, 0)])
    rep.update(order_Gamma=len(GAMMA), order_A6=len(A6))
    assert len(GAMMA) == 1440 and len(A6) == 360
    # ------------------------------------------------------------ circles and pencils
    base_circle = frozenset(IDX[x] for x in (INF, (0, 0), (1, 0), (2, 0)))
    circles = sorted({frozenset(g[i] for i in base_circle) for g in GAMMA}, key=sorted)
    pencils = {}
    for p in range(10):
        through = [c for c in circles if p in c]
        groups = []
        for c in through:
            for grp in groups:
                if all(len(c & c2) == 1 for c2 in grp):
                    grp.append(c)
                    break
            else:
                groups.append([c])
        pencils[p] = [frozenset(gp) for gp in groups]
    rep.update(circles=len(circles), pencil_sizes=sorted({(len(pencils[p]), len(x)) for p in pencils for x in pencils[p]}))
    assert len(circles) == 30 and all(len(pencils[p]) == 4 and all(len(x) == 3 for x in pencils[p]) for p in pencils)
    INFI = IDX[INF]

    def pencil_dir(d):          # the pencil at inf of the lines {x + t d}
        return frozenset(frozenset([INFI] + [IDX[add(x, mul((t, 0), d))] for t in range(3)]) for x in F)
    assert set(pencils[INFI]) == {pencil_dir(d) for d in (ONE, W, W2, pw(W, 3))}

    def moved(g, pen):
        return frozenset(frozenset(g[i] for i in c) for c in pen)
    # perpendicular pencils at inf: directions d, d' with (d'/d)^2 = -1; at p, transported by any g with g(inf) = p
    perp = set()
    dirs = [ONE, W, W2, pw(W, 3)]
    for d1, d2 in itertools.combinations(dirs, 2):
        q = mul(d2, inv(d1))
        if mul(q, q) == neg(ONE):
            perp.add(frozenset([pencil_dir(d1), pencil_dir(d2)]))
    for g in GAMMA:
        if g[INFI] == INFI:
            assert all(frozenset(moved(g, x) for x in pr) in perp for pr in list(perp))   # Gamma_inf-invariant
    perp_at = {}
    for g in GAMMA:
        perp_at.setdefault(g[INFI], set()).update(frozenset(moved(g, x) for x in pr) for pr in perp)
    assert all(len(perp_at[p]) == 2 for p in range(10))
    # ------------------------------------------------------------ the model points
    pentads = sorted({frozenset(o) for g in GAMMA if porder(g) == 5 for o in
                      [{i, g[i], g[g[i]], g[g[g[i]]], g[g[g[g[i]]]]} for i in range(10)]}, key=sorted)
    pairs = [(p, frozenset(pr)) for p in range(10) for pr in itertools.combinations(pencils[p], 2)
             if frozenset(pr) not in perp_at[p]]
    rep.update(pentads=len(pentads), pencil_pairs=len(pairs))
    assert len(pentads) == 72 and len(pairs) == 40

    def orbits(group, pts, act):
        lab, out = {}, []
        for x in pts:
            if x in lab:
                continue
            orb = {act(g, x) for g in group}
            for y in orb:
                lab[y] = len(out)
            out.append(orb)
        return lab, out
    act_pent = lambda g, O: frozenset(g[i] for i in O)
    act_pair = lambda g, b: (g[b[0]], frozenset(moved(g, x) for x in b[1]))
    labA, orbA = orbits(A6, pentads, act_pent)
    labB, orbB = orbits(A6, pairs, act_pair)
    rep.update(A6_orbits_on_pentads=[len(o) for o in orbA], A6_orbits_on_pairs=[len(o) for o in orbB])
    assert sorted(len(o) for o in orbA) == [36, 36] and sorted(len(o) for o in orbB) == [20, 20]

    def type_I(O, pen):
        return sum(1 for c in pen if len(c & O) == 3) == 1
    beta0 = (INFI, frozenset([pencil_dir(ONE), pencil_dir(W)]))
    assert beta0 in pairs
    sB = {b: (1 if labB[b] == labB[beta0] else -1) for b in pairs}
    O_plus = [O for O in pentads if INFI in O and all(type_I(O, x) for x in beta0[1])]
    assert O_plus and len({labA[O] for O in O_plus}) == 1
    sA = {O: (1 if labA[O] == labA[O_plus[0]] else -1) for O in pentads}
    pts = [("A", O) for O in pentads] + [("B", b) for b in pairs] + [("P", 1), ("P", -1), ("Q", 1), ("Q", -1)]
    n = len(pts)
    assert n == 116

    def sign(x):
        k, v = x
        return sA[v] if k == "A" else sB[v] if k == "B" else v

    def transport(p, q, pen):
        c = next(c for c in pen if q in c)
        return next(x for x in pencils[q] if c in x)

    def cls(x, y):
        (kx, vx), (ky, vy) = x, y
        if kx > ky:
            (kx, vx), (ky, vy) = (ky, vy), (kx, vx)
        if (kx, ky) == ("A", "A"):
            m = len(vx & vy)
            return {0: 12, 1: 5, 2: 12, 4: 5}[m] if m != 3 else (12 if sA[vx] == sA[vy] else 5)
        if (kx, ky) == ("B", "B"):
            (p, e), (q, f) = vx, vy
            if p == q:
                return 8 if not (e & f) else 2
            return 6 if frozenset(transport(p, q, x) for x in e) == f else 12
        if (kx, ky) == ("A", "B"):
            t = sum(type_I(vx, x) for x in vy[1])
            return {2: 3, 0: 10, 1: 12}[t]
        if (kx, ky) == ("A", "P"):
            return 9 if sA[vx] == vy else 12
        if (kx, ky) == ("A", "Q"):
            return 7 if sA[vx] == vy else 12
        if (kx, ky) == ("B", "P"):
            return 12 if sB[vx] == vy else 4
        if (kx, ky) == ("B", "Q"):
            return 12 if sB[vx] == vy else 11
        if (kx, ky) == ("P", "Q"):
            return 1 if vx == vy else 0
        if kx == ky:                                   # P x P, Q x Q
            return 12
        raise ValueError((kx, ky))
    CM = np.full((n, n), -1, dtype=np.int64)
    for i in range(n):
        for j in range(i + 1, n):
            CM[i, j] = CM[j, i] = cls(pts[i], pts[j])
    # ------------------------------------------------------------ (2) Gamma preserves the model class matrix
    index = {x: i for i, x in enumerate(pts)}

    def act_point(g, x):
        k, v = x
        if k == "A":
            return (k, act_pent(g, v))
        if k == "B":
            return (k, act_pair(g, v))
        return (k, v * (1 if g in M10set else -1))
    # eps(g) = +1 exactly for g in M10, the index-2 subgroup that preserves each A6-orbit on A
    A6set = set(A6)
    M10set = {g for g in GAMMA if all(labA[act_pent(g, O)] == labA[O] for O in pentads)}
    assert len(M10set) == 720 and A6set <= M10set
    ords = collections.Counter(porder(g) for g in M10set)
    rep["M10_element_orders"] = dict(sorted(ords.items()))
    assert 8 in ords and 6 not in ords and 10 not in ords          # M10, not S6 or PGL(2,9)
    inv_ok = True
    for g in GEN:
        perm = [index[act_point(g, x)] for x in pts]
        if sorted(perm) != list(range(n)) or not (CM[np.ix_(perm, perm)] == CM).all():
            inv_ok = False
    rep["Gamma_preserves_model_classes"] = inv_ok
    assert inv_ok
    # ------------------------------------------------------------ the contact graph on the pentads, exactly
    # N = adjacency of the contacts inside A; (N - 51)(N - 9)(N - 7)(N - 3)(N + 3) = 0 and the multiplicities of these
    # eigenvalues from the traces of N^0..N^4 (Vandermonde system, exact rationals): then G_AA = (c - t5)(N + 3I) + t5 J
    # vanishes on the (-3)-eigenspace exactly when 1 + 2 t5 = 3 c
    from fractions import Fraction
    iA = [i for i, x in enumerate(pts) if x[0] == "A"]
    N = [[int(CM[i, j] == 12) for j in iA] for i in iA]
    def mm(X_, Y_):
        return [[sum(a * b for a, b in zip(r, col)) for col in zip(*Y_)] for r in X_]
    I72 = [[int(i == j) for j in range(72)] for i in range(72)]
    ev = [51, 9, 7, 3, -3]
    Pm = I72
    for lam in ev:
        Pm = mm(Pm, [[N[i][j] - lam * I72[i][j] for j in range(72)] for i in range(72)])
    poly_zero = all(v == 0 for r in Pm for v in r)
    tr, Pk = [], I72
    for k in range(5):
        tr.append(sum(Pk[i][i] for i in range(72)))
        Pk = mm(Pk, N)
    V = [[Fraction(lam) ** k for lam in ev] for k in range(5)]
    # solve V m = tr exactly (Gauss-Jordan over Q)
    Mx = [row[:] + [Fraction(t_)] for row, t_ in zip(V, tr)]
    for c_ in range(5):
        pr = next(r for r in range(c_, 5) if Mx[r][c_] != 0)
        Mx[c_], Mx[pr] = Mx[pr], Mx[c_]
        Mx[c_] = [x / Mx[c_][c_] for x in Mx[c_]]
        for r in range(5):
            if r != c_ and Mx[r][c_] != 0:
                Mx[r] = [x - Mx[r][c_] * y for x, y in zip(Mx[r], Mx[c_])]
    mult = [Mx[r][5] for r in range(5)]
    rep["pentad_contact_graph"] = {"degree": sum(N[0]), "eigenvalues": ev, "polynomial_identity": poly_zero,
                                   "multiplicities": [str(m) for m in mult]}
    assert poly_zero and mult == [1, 1, 9, 10, 51] and all(sum(r) == 51 for r in N)
    # ------------------------------------------------------------ (3) comparison with X*
    C = load_classes()
    rep["class_matrix_sha256"] = hashlib.sha256(open(os.path.join(HERE, "data", "class_matrix.gp"), "rb").read()).hexdigest()
    rep["class_counts_model"] = {str(k): int((CM == k).sum() // 2) for k in range(13)}
    rep["class_counts_Xstar"] = {str(k): int((C == k).sum() // 2) for k in range(13)}
    g = isomorphism(C, CM)
    ok = g is not None and sorted(int(x) for x in g) == list(range(n)) and bool((CM[np.ix_(g, g)] == C).all())
    rep["model_equals_Xstar_classes"] = ok
    if g is not None:
        def name(x):
            k, v = x
            if k == "A":
                return "A:" + ",".join(map(str, sorted(v)))
            if k == "B":
                return "B:%d:%s" % (v[0], ",".join(str(pencils[v[0]].index(pen)) for pen in sorted(v[1], key=pencils[v[0]].index)))
            return "%s%s" % (k, "+" if v > 0 else "-")
        rep["relabelling_Xstar_point_to_model_point"] = [name(pts[int(x)]) for x in g]
        rep["signs_of_Xstar_points"] = [sign(pts[int(x)]) for x in g]
    rep["seconds"] = round(time.time() - t0, 1)
    json.dump(rep, open(os.path.join(HERE, "out", "construct.json"), "w"), indent=1)
    print(json.dumps({k: v for k, v in rep.items() if not k.startswith(("relabelling", "signs"))}))
    if not ok:
        raise SystemExit("the model does not reproduce the class matrix of X*")


if __name__ == "__main__":
    main()
